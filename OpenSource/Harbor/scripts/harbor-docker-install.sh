#!/bin/bash
set -euo pipefail
# =============================================================================
# Harbor Docker Install Script
# =============================================================================
# Follows Harbor's official installation guide with the ONLINE installer,
# behind a host Nginx reverse proxy:
#
#   1. Download harbor-online-installer-<version>.tgz from the GitHub release
#      and verify it with cosign, if installed (docs/signature-verification.md
#      in the Harbor repo - releases are signed from v2.15.0)
#   2. cp harbor.yml.tmpl harbor.yml and set the values below
#   3. sudo ./install.sh [--with-trivy] - run unmodified. It runs ./prepare,
#      which renders harbor.yml into docker-compose.yml and common/config/,
#      then `docker compose up -d`, which pulls the images from Docker Hub
#
#   /var/www/docker/harbor/<domain>/
#     |-- harbor/                  the official installer, extracted
#     |   |-- harbor.yml           written here (mode 600) - the config file
#     |   |-- install.sh, prepare, common.sh, harbor.yml.tmpl, LICENSE
#     |   |-- docker-compose.yml   generated by ./prepare - do not edit
#     |   `-- common/config/       generated by ./prepare - do not edit
#     |-- data/                    data_volume: database, image storage,
#     |                            secret keys, redis, job logs, Trivy cache
#     `-- logs/                    log.local.location: one file per component
#
# harbor.yml is harbor.yml.tmpl with only these lines changed. Each change is an
# exact whole-line match, and the script stops if the template has changed
# instead of guessing:
#
#   hostname               <domain>
#   http.port              "127.0.0.1:<port>"
#   https:                 commented out - the host Nginx terminates TLS
#   external_url           https://<domain>
#   harbor_admin_password  asked, or generated
#   database.password      asked, or generated
#   data_volume            <instance>/data
#   log.local.location     <instance>/logs
#
# WHY http.port HOLDS AN ADDRESS. ./prepare copies http.port verbatim into the
# proxy service's port mapping ("{{http_port}}:8080"), so "127.0.0.1:8095"
# becomes "127.0.0.1:8095:8080" and Harbor is reachable from this host only.
# Because the address lives in harbor.yml, it survives every later ./prepare
# (reconfigure, upgrade). An edit to the generated docker-compose.yml would be
# silently undone by the next ./prepare, putting Harbor back on 0.0.0.0, and
# Docker-published ports bypass ufw.
#
# ONE INSTANCE PER HOST. Harbor's compose file hard-codes its container names
# (nginx, redis, registry, harbor-core, harbor-db, harbor-log, ...) and the log
# collector's 127.0.0.1:1514. The domain still names the directory, so the
# layout matches the other apps, but a second Harbor on this Docker host is
# refused.
#
# FRESH INSTALLS ONLY. install.sh always runs `docker compose down -v` before
# starting, so this script refuses a non-empty instance directory. To change
# the configuration later, see Harbor.md -> Reconfigure.
# =============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
NGINX_CONF_SRC="$SCRIPT_DIR/../harbor-nginx.conf"

HARBOR_BASE="/var/www/docker/harbor"
DEFAULT_PORT="8095"
MIN_VERSION="v2.15.0"
RELEASES_API="https://api.github.com/repos/goharbor/harbor/releases/latest"
RELEASES_DL="https://github.com/goharbor/harbor/releases/download"

# Every container name Harbor's compose file can create (trivy-adapter only
# with --with-trivy, harbor-exporter only with metrics enabled).
HARBOR_CONTAINERS=(harbor-log registry registryctl harbor-db harbor-core
                   harbor-portal harbor-jobservice redis nginx trivy-adapter
                   harbor-exporter)

# ── Helpers ───────────────────────────────────────────────────────────────────

_die() { echo "ERROR: $*" >&2; exit 1; }

_mask() { [[ -n "${1:-}" ]] && echo "(set, ${#1} chars)" || echo "(empty)"; }

_valid_domain() {
  [[ "$1" =~ ^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?)+$ ]]
}

_valid_port() {
  [[ "$1" =~ ^[0-9]+$ ]] && [ "$1" -ge 1 ] && [ "$1" -le 65535 ]
}

_port_in_use() {  # _port_in_use <port>
  ss -ltnH 2>/dev/null | awk '{print $4}' | grep -qE "[:.]${1}$"
}

# Passwords end up in harbor.yml (YAML), in the env files ./prepare generates
# (read by Compose's env_file parser, which expands $), and in the SQL that
# sets the database password on first start. Only characters that are plain in
# all three - URL-unreserved - are accepted, so nothing has to be escaped.
_valid_secret() {
  [[ "$1" =~ ^[A-Za-z0-9._~-]{8,128}$ ]]
}

# Harbor's password policy for the admin account: 8-128 characters with at
# least one uppercase letter, one lowercase letter and one digit.
_valid_admin_secret() {
  _valid_secret "$1" && [[ "$1" =~ [[:upper:]] ]] && [[ "$1" =~ [[:lower:]] ]] && [[ "$1" =~ [[:digit:]] ]]
}

# 24 alphanumerics, retried until all three character classes are present.
_gen_secret() {
  local s
  while :; do
    s="$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | cut -c1-24)"
    _valid_admin_secret "$s" && { echo "$s"; return 0; }
  done
}

_ask_secret() {  # _ask_secret <var-name> <label> <validator> <rule>
  local -n _ref="$1"
  local label="$2" validator="$3" rule="$4" first second
  while :; do
    read -rsp "  ${label} (blank = generate a strong one): " first; echo
    if [[ -z "$first" ]]; then
      _ref="$(_gen_secret)"
      echo "    Generated: ${_ref}"
      return 0
    fi
    read -rsp "  Confirm ${label}: " second; echo
    if [[ "$first" != "$second" ]]; then
      echo "    Values do not match - try again."
      continue
    fi
    if ! "$validator" "$first"; then
      echo "    Rejected. $rule"
      continue
    fi
    _ref="$first"
    return 0
  done
}

_version_ge() {  # _version_ge <a> <b>  ->  true when a >= b
  [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | head -n1)" = "$2" ]
}

# Replace one line of harbor.yml by exact whole-line match. Dies unless the line
# is there exactly once - anything else means the template changed and this
# script needs a look.
_yml_edit() {  # _yml_edit <exact line> <replacement line>
  local old="$1" new="$2" line count tmp
  count="$(grep -cxF -- "$old" "$HARBOR_YML" || true)"
  [ "$count" = "1" ] || \
    _die "harbor.yml.tmpl ($version) has ${count} line(s) equal to '$old', expected 1 - the template changed; update $(basename "$0")."
  tmp="$(mktemp)"
  while IFS= read -r line || [[ -n "$line" ]]; do
    if [[ "$line" == "$old" ]]; then
      printf '%s\n' "$new" >> "$tmp"
    else
      printf '%s\n' "$line" >> "$tmp"
    fi
  done < "$HARBOR_YML"
  cat "$tmp" > "$HARBOR_YML"   # rewrite in place so the file keeps its 600 mode
  rm -f "$tmp"
}

# ── Dependency check ──────────────────────────────────────────────────────────
# Docker first: every step below runs through it.
command -v docker >/dev/null 2>&1 \
  || _die "Docker is not installed. Install Docker Engine (https://docs.docker.com/engine/install/), then run this script again."
docker compose version >/dev/null 2>&1 \
  || _die "the Docker Compose plugin ('docker compose') is not installed. Install it (https://docs.docker.com/compose/install/linux/), then run this script again."
docker info >/dev/null 2>&1 \
  || _die "cannot talk to Docker - is it running, and is $(id -un) in the docker group?"
for cmd in curl openssl tar ss sed awk sort mktemp; do
  command -v "$cmd" >/dev/null 2>&1 || _die "'$cmd' is required but not installed."
done

echo ""
echo "=====> Harbor Install (online installer)"
echo "========================================"
echo ""

# ── One Harbor per host ───────────────────────────────────────────────────────
mapfile -t EXISTING < <(docker ps -a --format '{{.Names}}' \
  | grep -xE "$(IFS='|'; echo "${HARBOR_CONTAINERS[*]}")" || true)
if [ ${#EXISTING[@]} -gt 0 ]; then
  echo "Containers with Harbor's fixed names already exist on this host:"
  for c in "${EXISTING[@]}"; do
    wd="$(docker inspect -f '{{index .Config.Labels "com.docker.compose.project.working_dir"}}' "$c" 2>/dev/null || true)"
    printf "  %-18s %s\n" "$c" "${wd:-(not started by Compose)}"
  done
  _die "Harbor hard-codes its container names, so only one instance fits on a Docker host. Remove the existing one first."
fi

if [ -d "$HARBOR_BASE" ]; then
  mapfile -t OTHER_INSTANCES < <(find "$HARBOR_BASE" -mindepth 3 -maxdepth 3 -path '*/harbor/harbor.yml' 2>/dev/null || true)
  if [ ${#OTHER_INSTANCES[@]} -gt 0 ]; then
    printf '  %s\n' "${OTHER_INSTANCES[@]}"
    _die "an instance directory already exists under $HARBOR_BASE (above). One Harbor per host - remove it first."
  fi
fi

if _port_in_use 1514; then
  ss -ltnp 2>/dev/null | grep -E "[:.]1514[[:space:]]" || true
  _die "port 1514 is in use. Harbor's log collector publishes 127.0.0.1:1514 and every other Harbor container logs through it."
fi

# ── Prerequisites ────────────────────────────────────────────────────────────
# Confirmed by the person running this: the Nginx site expects the certificate
# in /etc/letsencrypt/live/<domain>/, and certbot only issues it once the DNS
# record points here.
echo "Before you continue, make sure that:"
echo "  1. A DNS record for the Harbor domain points at this server."
echo "  2. A Let's Encrypt certificate for the Harbor domain exists in"
echo "     /etc/letsencrypt/live/<domain>/."
echo ""
read -rp "Type 'yes' to confirm both and continue: " ans_prereq
[[ "${ans_prereq,,}" == "yes" ]] || _die "Aborted - set these up first, then run this script again."
echo ""

# ── Domain ────────────────────────────────────────────────────────────────────
echo "Harbor issues registry tokens and pull/push URLs against this name, so it"
echo "must be the public name clients use (docker login <domain>)."
read -rp "Enter domain name (e.g. harbor.example.com): " domain
[[ -n "$domain" ]] || _die "Domain cannot be empty."
_valid_domain "$domain" || _die "'$domain' is not a valid domain name."
domain="${domain,,}"

INSTALL_DIR="$HARBOR_BASE/$domain"
if [ -e "$INSTALL_DIR" ] && [ -n "$(ls -A "$INSTALL_DIR" 2>/dev/null)" ]; then
  _die "$INSTALL_DIR already exists and is not empty - remove that instance first, or use another domain."
fi

# ── Port ──────────────────────────────────────────────────────────────────────
echo ""
echo "Harbor is published on 127.0.0.1:<port> and proxied by Nginx."
read -rp "Enter host port for Harbor [$DEFAULT_PORT]: " port
port="${port:-$DEFAULT_PORT}"
_valid_port "$port" || _die "Port must be a number between 1 and 65535."
[ "$port" != "1514" ] || _die "Port 1514 is reserved for Harbor's log collector."

if _port_in_use "$port"; then
  echo ""
  echo "WARNING: something is already listening on port $port:"
  ss -ltnp 2>/dev/null | grep -E "[:.]${port}[[:space:]]" || true
  read -rp "Continue anyway? [y/N] " ans_port
  [[ "$ans_port" =~ ^[Yy]$ ]] || _die "Aborted - pick a free port."
fi

# ── Version ───────────────────────────────────────────────────────────────────
echo ""
latest="$(curl -fsSL --max-time 15 "$RELEASES_API" 2>/dev/null \
  | sed -n 's/^[[:space:]]*"tag_name":[[:space:]]*"\([^"]*\)".*/\1/p' | head -n1 || true)"
if [[ -n "$latest" ]]; then
  read -rp "Harbor version [$latest]: " version
  version="${version:-$latest}"
else
  echo "Could not look up the latest release on GitHub."
  read -rp "Harbor version (e.g. v2.15.4): " version
fi
[[ -n "$version" ]] || _die "Version cannot be empty."
[[ "$version" == v* ]] || version="v$version"
[[ "$version" =~ ^v[0-9]+\.[0-9]+\.[0-9]+(-rc[0-9]+)?$ ]] || _die "'$version' is not a Harbor release tag (vX.Y.Z)."
_version_ge "$version" "$MIN_VERSION" || \
  _die "$version is older than $MIN_VERSION. This script is written against the $MIN_VERSION+ harbor.yml template and signed releases."

INSTALLER="harbor-online-installer-${version}.tgz"
INSTALLER_URL="$RELEASES_DL/${version}/${INSTALLER}"

# ── Trivy ─────────────────────────────────────────────────────────────────────
echo ""
echo "Trivy is Harbor's built-in vulnerability scanner (install.sh --with-trivy)."
read -rp "Enable Trivy? [Y/n] " ans_trivy
if [[ "$ans_trivy" =~ ^[Nn]$ ]]; then with_trivy=false; else with_trivy=true; fi

# ── Credentials ───────────────────────────────────────────────────────────────
admin_password=""
db_password=""
echo ""
echo "==> Credentials (allowed characters: A-Z a-z 0-9 . _ ~ -):"
echo "    The admin password is only applied on first start - after that it lives"
echo "    in the database and is changed from the UI."
_ask_secret admin_password "Harbor admin password" _valid_admin_secret \
  "Use 8-128 characters from A-Z a-z 0-9 . _ ~ - with at least one uppercase letter, one lowercase letter and one digit."
_ask_secret db_password "Harbor database password" _valid_secret \
  "Use 8-128 characters from A-Z a-z 0-9 . _ ~ -"

# ── Signature verification ────────────────────────────────────────────────────
# Harbor signs with Sigstore's newer bundle format. cosign v2.5+ reads it with
# the documented command as-is; v2.4.x only with --new-bundle-format; anything
# older cannot read it at all and would report a valid file as a bad signature.
echo ""
verify_sig=false
COSIGN_ARGS=()
cosign_ver=""
command -v cosign >/dev/null 2>&1 && \
  cosign_ver="$(cosign version 2>/dev/null | sed -n 's/^GitVersion:[[:space:]]*//p' | head -n1 || true)"
if [[ -n "$cosign_ver" ]] && _version_ge "$cosign_ver" v2.4.0; then
  verify_sig=true
  _version_ge "$cosign_ver" v2.5.0 || COSIGN_ARGS=(--new-bundle-format)
  sig_status="cosign $cosign_ver"
else
  if command -v cosign >/dev/null 2>&1; then
    sig_status="SKIPPED - cosign ${cosign_ver:-(unknown version)} is older than v2.4.0"
    echo "WARNING: cosign ${cosign_ver:-(unknown version)} cannot read Harbor's signature bundles."
    echo "         Upgrade cosign (see Harbor.md) to verify the installer."
  else
    sig_status="SKIPPED - cosign not installed"
    echo "WARNING: cosign is not installed, so the installer's signature cannot be"
    echo "         verified. To verify, install cosign (see Harbor.md) and re-run."
  fi
  read -rp "Continue without verifying the signature? [y/N] " ans_sig
  [[ "$ans_sig" =~ ^[Yy]$ ]] || _die "Aborted - install cosign and re-run."
fi

# ── Summary ───────────────────────────────────────────────────────────────────
DATA_DIR="$INSTALL_DIR/data"
LOG_DIR="$INSTALL_DIR/logs"
HARBOR_DIR="$INSTALL_DIR/harbor"
HARBOR_YML="$HARBOR_DIR/harbor.yml"

echo ""
echo "==================== SUMMARY ===================="
echo "Domain          : $domain"
echo "URL             : https://$domain"
echo "Host port       : 127.0.0.1:$port"
echo "Harbor version  : $version (online installer)"
echo "Trivy           : $( $with_trivy && echo "enabled (--with-trivy)" || echo "disabled" )"
echo "Signature check : $sig_status"
echo "Install dir     : $INSTALL_DIR"
echo "  installer     : $HARBOR_DIR"
echo "  data_volume   : $DATA_DIR"
echo "  logs          : $LOG_DIR"
echo "Admin user      : admin"
echo "Admin password  : $(_mask "$admin_password")"
echo "DB password     : $(_mask "$db_password")"
echo "================================================="
echo ""
read -rp "Proceed? [Y/n] " ans_proceed
[[ "$ans_proceed" =~ ^[Nn]$ ]] && { echo "Aborted."; exit 0; }

# ── Download (and verify) the installer ───────────────────────────────────────
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

echo ""
echo "==> Downloading $INSTALLER"
curl -fL --retry 3 --progress-bar -o "$TMP_DIR/$INSTALLER" "$INSTALLER_URL" \
  || _die "download failed: $INSTALLER_URL"

if $verify_sig; then
  echo "==> Verifying the signature (cosign verify-blob)"
  curl -fsSL --retry 3 -o "$TMP_DIR/$INSTALLER.sigstore.json" "$INSTALLER_URL.sigstore.json" \
    || _die "could not download $INSTALLER.sigstore.json"
  cosign verify-blob ${COSIGN_ARGS[@]+"${COSIGN_ARGS[@]}"} \
    --bundle "$TMP_DIR/$INSTALLER.sigstore.json" \
    --certificate-oidc-issuer https://token.actions.githubusercontent.com \
    --certificate-identity-regexp '^https://github.com/goharbor/harbor/.github/workflows/publish_release.yml@refs/tags/v.*$' \
    "$TMP_DIR/$INSTALLER" \
    || _die "signature verification FAILED for $INSTALLER - do not use this file."
fi

# ── Extract into the instance directory ───────────────────────────────────────
echo "==> Extracting into $INSTALL_DIR"
sudo mkdir -p "$INSTALL_DIR"
sudo chown "$(id -u):$(id -g)" "$INSTALL_DIR"
chmod 750 "$INSTALL_DIR"
tar -xzf "$TMP_DIR/$INSTALLER" -C "$INSTALL_DIR"
for f in install.sh prepare common.sh harbor.yml.tmpl; do
  [ -f "$HARBOR_DIR/$f" ] || _die "$f is missing from $INSTALLER."
done

# ── Write harbor.yml ──────────────────────────────────────────────────────────
echo "==> Writing harbor.yml"
touch "$HARBOR_YML"
chmod 600 "$HARBOR_YML"   # holds the admin and database passwords
cat "$HARBOR_DIR/harbor.yml.tmpl" > "$HARBOR_YML"

_yml_edit 'hostname: reg.mydomain.com'                     "hostname: $domain"
_yml_edit '  port: 80'                                     "  port: \"127.0.0.1:$port\""
_yml_edit 'https:'                                         '# https:'
_yml_edit '  port: 443'                                    '#   port: 443'
_yml_edit '  certificate: /your/certificate/path'          '#   certificate: /your/certificate/path'
_yml_edit '  private_key: /your/private/key/path'          '#   private_key: /your/private/key/path'
_yml_edit '# external_url: https://reg.mydomain.com:8433'  "external_url: https://$domain"
_yml_edit 'harbor_admin_password: Harbor12345'             "harbor_admin_password: \"$admin_password\""
_yml_edit '  password: root123'                            "  password: \"$db_password\""
_yml_edit 'data_volume: /data'                             "data_volume: $DATA_DIR"
_yml_edit '    location: /var/log/harbor'                  "    location: $LOG_DIR"
echo "==> harbor.yml written to $HARBOR_YML (mode 600)"

read -rp "Would you like to review/edit harbor.yml? [y/N] " ans_yml
[[ "$ans_yml" =~ ^[Yy]$ ]] && "${EDITOR:-vim}" "$HARBOR_YML"

# ── Run the official installer ────────────────────────────────────────────────
INSTALL_ARGS=()
$with_trivy && INSTALL_ARGS+=(--with-trivy)

echo ""
echo "==> Running: sudo ./install.sh ${INSTALL_ARGS[*]:-}"
echo "    (./prepare renders the config, then Compose pulls the images - this takes a few minutes)"
cd "$HARBOR_DIR"
sudo ./install.sh ${INSTALL_ARGS[@]+"${INSTALL_ARGS[@]}"}

# ── Confirm the proxy is on loopback only ─────────────────────────────────────
PUBLISHED="$(docker port nginx 8080/tcp 2>/dev/null || true)"
if [[ "$PUBLISHED" != "127.0.0.1:$port" ]]; then
  echo ""
  echo "WARNING: Harbor's proxy is published on '${PUBLISHED:-nothing}', expected 127.0.0.1:$port."
  echo "         Check http.port in $HARBOR_YML, then re-run ./prepare (Harbor.md -> Reconfigure)."
fi

# ── Wait for Harbor to answer ─────────────────────────────────────────────────
echo -n "==> Waiting for Harbor to respond on 127.0.0.1:$port"
HARBOR_UP=false
for _ in $(seq 1 60); do
  if [ "$(curl -fsS --max-time 5 "http://127.0.0.1:${port}/api/v2.0/ping" 2>/dev/null || true)" = "Pong" ]; then
    HARBOR_UP=true
    break
  fi
  echo -n "."
  sleep 5
done
echo ""

if $HARBOR_UP; then
  echo "==> Harbor is up."
else
  echo "WARNING: Harbor did not answer within ~5 minutes. Check the logs:"
  echo "           cd $HARBOR_DIR && sudo docker compose ps"
  echo "           sudo tail -n 50 $LOG_DIR/core.log"
  read -rp "Continue with the Nginx setup anyway? [y/N] " ans_continue
  [[ "$ans_continue" =~ ^[Yy]$ ]] || exit 1
fi

# ── Let's Encrypt ─────────────────────────────────────────────────────────────
echo ""
read -rp "Would you like to obtain a Let's Encrypt certificate now? [y/N] " ans_cert
if [[ "$ans_cert" =~ ^[Yy]$ ]]; then
  sudo certbot certonly --nginx -d "$domain"
fi

# ── Nginx reverse proxy ───────────────────────────────────────────────────────
read -rp "Would you like to set up the Nginx reverse proxy? [y/N] " ans_nginx
if [[ "$ans_nginx" =~ ^[Yy]$ ]]; then
  NGINX_AVAIL="/etc/nginx/sites-available/$domain"

  [[ -f "$NGINX_CONF_SRC" ]] || _die "nginx config template not found at $NGINX_CONF_SRC"

  sudo cp "$NGINX_CONF_SRC" "$NGINX_AVAIL"
  sudo sed -i \
    -e "s|harbor\.example\.com|$domain|g" \
    -e "s|127\.0\.0\.1:8095|127.0.0.1:$port|g" \
    "$NGINX_AVAIL"
  echo "==> Nginx config written to $NGINX_AVAIL"

  read -rp "Would you like to enable the site (link to sites-enabled)? [y/N] " ans_link
  if [[ "$ans_link" =~ ^[Yy]$ ]]; then
    sudo ln -sf "$NGINX_AVAIL" "/etc/nginx/sites-enabled/$domain"
    echo "==> Symlink created."
  fi

  echo "==> Testing Nginx configuration..."
  sudo nginx -t
  echo "==> Reloading Nginx..."
  sudo systemctl reload nginx
  echo "==> Nginx reloaded."
fi

# ── Done ──────────────────────────────────────────────────────────────────────
echo ""
echo "==> Harbor installation complete."
echo "    URL            : https://$domain"
echo "    Admin user     : admin  (password: harbor_admin_password in harbor.yml -"
echo "                     change it in the UI after first login)"
echo "    Docker login   : docker login $domain"
echo "    Push           : docker tag <image> $domain/library/<image>:<tag>"
echo "                     docker push $domain/library/<image>:<tag>"
echo ""
echo "    Install dir    : $INSTALL_DIR"
echo "    Config         : $HARBOR_YML (mode 600 - back this up)"
echo "    Data           : $DATA_DIR"
echo "    Logs           : $LOG_DIR"
echo ""
echo "    Useful commands (run from $HARBOR_DIR - they need sudo, because"
echo "    ./prepare writes Harbor's env files readable by root only):"
echo "    Status  : sudo docker compose ps"
echo "    Stop    : sudo docker compose down"
echo "    Start   : sudo docker compose up -d"
echo "    Logs    : sudo tail -f $LOG_DIR/core.log"
echo "    Reconfigure: sudo docker compose down && \$EDITOR harbor.yml \\"
echo "                 && sudo ./prepare$( $with_trivy && echo " --with-trivy" ) && sudo docker compose up -d"
echo ""
echo "    Back up with : $SCRIPT_DIR/harbor-docker-backup.sh"
echo "    Restore with : $SCRIPT_DIR/harbor-docker-restore.sh"
